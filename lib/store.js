const fs = require("fs");
const path = require("path");

function carregarEnvLocal() {
  if (process.env.DATABASE_URL || process.env.POSTGRES_URL) return;
  const file = path.join(__dirname, "..", ".env.local");
  if (!fs.existsSync(file)) return;
  fs.readFileSync(file, "utf8")
    .split(/\r?\n/)
    .forEach((line) => {
      const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (!match || process.env[match[1]]) return;
      process.env[match[1]] = match[2].replace(/^"|"$/g, "");
    });
}

carregarEnvLocal();

function databaseUrl() {
  return process.env.DATABASE_URL || process.env.POSTGRES_URL || "";
}

function mapRow(row) {
  let itens = row.itens;
  if (typeof itens === "string") {
    try {
      itens = JSON.parse(itens);
    } catch {
      itens = [];
    }
  }
  const data = row.data_evento || row.dataEvento;
  return {
    id: Number(row.id),
    nome: row.nome,
    telefone: row.telefone,
    dataEvento: String(data).slice(0, 10),
    pessoas: row.pessoas,
    local: row.local,
    observacoes: row.observacoes || "",
    itens: Array.isArray(itens) ? itens : [],
    total: row.total == null ? null : Number(row.total),
    criadoEm: new Date(row.criado_em || row.criadoEm).toISOString(),
  };
}

let neonReady;

async function neonSql() {
  const url = databaseUrl();
  if (!url) return null;
  if (!neonReady) {
    const { neon } = require("@neondatabase/serverless");
    const sql = neon(url);
    neonReady = sql`CREATE TABLE IF NOT EXISTS pedidos (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome TEXT NOT NULL,
      telefone TEXT NOT NULL,
      data_evento TEXT NOT NULL,
      pessoas INTEGER NOT NULL,
      local TEXT NOT NULL,
      observacoes TEXT NOT NULL DEFAULT '',
      itens JSONB NOT NULL,
      total DOUBLE PRECISION,
      criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )`
      .then(() => sql`ALTER TABLE pedidos ALTER COLUMN total DROP NOT NULL`)
      .then(() => sql);
  }
  return neonReady;
}

function sqliteDb() {
  const { DatabaseSync } = require("node:sqlite");
  const dir = path.join(__dirname, "..", "data");
  fs.mkdirSync(dir, { recursive: true });
  const db = new DatabaseSync(path.join(dir, "pedidos.sqlite"));
  db.exec(`
    CREATE TABLE IF NOT EXISTS pedidos (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      nome TEXT NOT NULL,
      telefone TEXT NOT NULL,
      tipo TEXT NOT NULL DEFAULT 'Retirada',
      data_evento TEXT NOT NULL,
      pessoas INTEGER,
      atendimento TEXT NOT NULL DEFAULT 'retirada',
      local TEXT NOT NULL,
      observacoes TEXT NOT NULL,
      criado_em TEXT NOT NULL,
      itens TEXT NOT NULL DEFAULT '[]',
      total REAL
    )
  `);
  return db;
}

async function criarPedido(pedido) {
  const sql = await neonSql();
  const criadoEm = new Date().toISOString();
  if (sql) {
    const rows = await sql`
      INSERT INTO pedidos (nome, telefone, data_evento, pessoas, local, observacoes, itens, total, criado_em)
      VALUES (
        ${pedido.nome},
        ${pedido.telefone},
        ${pedido.dataEvento},
        ${pedido.pessoas},
        ${pedido.local},
        ${pedido.observacoes},
        ${JSON.stringify(pedido.itens)}::jsonb,
        ${pedido.total},
        ${criadoEm}
      )
      RETURNING id, nome, telefone, data_evento, pessoas, local, observacoes, itens, total, criado_em
    `;
    return mapRow(rows[0]);
  }

  const db = sqliteDb();
  const result = db
    .prepare(
      `INSERT INTO pedidos
        (nome, telefone, tipo, data_evento, pessoas, atendimento, local, observacoes, criado_em, itens, total)
       VALUES (?, ?, 'Retirada', ?, ?, 'retirada', ?, ?, ?, ?, ?)`
    )
    .run(
      pedido.nome,
      pedido.telefone,
      pedido.dataEvento,
      pedido.pessoas,
      pedido.local,
      pedido.observacoes,
      criadoEm,
      JSON.stringify(pedido.itens),
      pedido.total
    );
  return mapRow({
    id: Number(result.lastInsertRowid),
    ...pedido,
    data_evento: pedido.dataEvento,
    criado_em: criadoEm,
    itens: pedido.itens,
  });
}

async function pedidosPorTelefone(telefone) {
  const sql = await neonSql();
  if (sql) {
    const rows = await sql`
      SELECT id, nome, telefone, data_evento, pessoas, local, observacoes, itens, total, criado_em
      FROM pedidos
      WHERE telefone = ${telefone}
      ORDER BY id DESC
    `;
    return rows.map(mapRow);
  }
  return sqliteDb()
    .prepare("SELECT * FROM pedidos WHERE telefone = ? ORDER BY id DESC")
    .all(telefone)
    .map(mapRow);
}

async function todosPedidos() {
  const sql = await neonSql();
  if (sql) {
    const rows = await sql`
      SELECT id, nome, telefone, data_evento, pessoas, local, observacoes, itens, total, criado_em
      FROM pedidos
      ORDER BY id DESC
    `;
    return rows.map(mapRow);
  }
  return sqliteDb().prepare("SELECT * FROM pedidos ORDER BY id DESC").all().map(mapRow);
}

module.exports = { criarPedido, pedidosPorTelefone, todosPedidos };
